export function RenderBadge({ badge, theme = "cyan" }) {
  if (!badge) return null;
  const isRed = theme === "red";
  if (badge.type === "top3" || badge.icon === "👑") {
    return (
      <span title="TOP 3" style={{ display: "inline-flex", alignItems: "center", gap: 3, padding: "1px 5px", borderRadius: 2, background: "rgba(255,215,0,0.12)", border: "1px solid rgba(255,215,0,0.4)", color: "#ffd700", fontSize: 9, fontFamily: "'Orbitron',monospace", letterSpacing: "0.06em", verticalAlign: "middle" }}>
        <CrownIcon size={10} color="#ffd700" /> TOP 3
      </span>
    );
  }
  if (badge.type === "rising" || badge.icon === "🔥") {
    return (
      <span title="RISING" style={{ display: "inline-flex", alignItems: "center", gap: 3, padding: "1px 5px", borderRadius: 2, background: isRed ? "rgba(255,100,50,0.12)" : "rgba(0,255,170,0.12)", border: isRed ? "1px solid rgba(255,100,50,0.4)" : "1px solid rgba(0,255,170,0.4)", color: isRed ? "#ff7744" : "#00ffaa", fontSize: 9, fontFamily: "'Orbitron',monospace", letterSpacing: "0.06em", verticalAlign: "middle" }}>
        <FlameIcon size={10} color={isRed ? "#ff7744" : "#00ffaa"} /> RISING
      </span>
    );
  }
  if (badge.type === "climber" || badge.icon === "⚡") {
    return (
      <span title="CLIMBER" style={{ display: "inline-flex", alignItems: "center", gap: 3, padding: "1px 5px", borderRadius: 2, background: isRed ? "rgba(255,60,0,0.12)" : "rgba(0,170,255,0.12)", border: isRed ? "1px solid rgba(255,60,0,0.4)" : "1px solid rgba(0,170,255,0.4)", color: isRed ? "#ff5522" : "#00aaff", fontSize: 9, fontFamily: "'Orbitron',monospace", letterSpacing: "0.06em", verticalAlign: "middle" }}>
        <ZapIcon size={10} color={isRed ? "#ff5522" : "#00aaff"} /> CLIMBER
      </span>
    );
  }
  if (badge.type === "rookie" || badge.icon === "🆕") {
    return (
      <span title="ROOKIE" style={{ display: "inline-flex", alignItems: "center", gap: 3, padding: "1px 5px", borderRadius: 2, background: "rgba(180,100,255,0.12)", border: "1px solid rgba(180,100,255,0.4)", color: "#c084fc", fontSize: 9, fontFamily: "'Orbitron',monospace", letterSpacing: "0.06em", verticalAlign: "middle" }}>
        <SparklesIcon size={10} color="#c084fc" /> NEW
      </span>
    );
  }
  return null;
}
